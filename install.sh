#!/usr/bin/env bash
# Скрипт установки окружения для Linux / macOS

set -e

echo "========================================================"
echo " Установка окружения для проекта «Цифровой Двойник Карьера»"
echo "========================================================"

if ! command -v python3 &> /dev/null; then
    echo "[ОШИБКА] python3 не найден! Установите Python 3.10+."
    exit 1
fi

if [ ! -d ".venv" ]; then
    echo "[*] Создание виртуального окружения .venv..."
    python3 -m venv .venv
else
    echo "[*] Виртуальное окружение .venv уже существует."
fi

echo "[*] Установка зависимостей..."
source .venv/bin/activate
pip install --upgrade pip
pip install -r requirements.txt

echo "========================================================"
echo " Установка успешно завершена!"
echo " Для запуска выполните: ./run.sh"
echo "========================================================"
